#!/usr/bin/env python3
"""Generate codepoint range tables for Unicode general categories L, M, N and White_Space."""
import sys, unicodedata
def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out
cat = lambda cp: unicodedata.category(chr(cp))
ws = {0x09,0x0A,0x0B,0x0C,0x0D,0x20,0x85,0xA0,0x1680,0x2028,0x2029,0x202F,0x205F,0x3000} | set(range(0x2000, 0x200B))
tables = {"L": lambda cp: cat(cp)[0] == "L", "M": lambda cp: cat(cp)[0] == "M",
          "N": lambda cp: cat(cp)[0] == "N", "WS": lambda cp: cp in ws}
lines = [f"// Generated by scripts/gen_unicode.py (Python unicodedata {unicodedata.unidata_version}). Do not edit."]
for name, pred in tables.items():
    r = ranges(pred)
    lines.append(f"static const uint32_t kUni_{name}[][2] = {{")
    lines.append(",".join(f"{{0x{a:X},0x{b:X}}}" for a, b in r))
    lines.append("};")
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
print("ok", {k: len(ranges(v)) for k, v in tables.items()})
